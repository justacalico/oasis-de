int? evdevCodeFor(PhysicalKeyboardKey key) {
  final usage = key.usbHidUsage;
  final page = (usage >> 16) & 0xFFFF;
  final id = usage & 0xFFFF;
  if (page == 0x0C) return _consumerToEvdev[id];
  return _hidToEvdev[id];
}
